// Writes src/copy.js (country names in every app language) from the string
// catalogue the apps use, so a push says "Norge" where the app says "Norge".
//   node scripts/gen-copy.mjs          write src/copy.js
//   node scripts/gen-copy.mjs --check  exit 1 when src/copy.js is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const catalogue = join(here, "..", "..", "NordicCrypto", "Localizable.xcstrings");
const out = join(here, "..", "src", "copy.js");

// The app's language codes (AppLanguage in Models.swift, Lang.kt).
export const LANGS = ["en", "nb", "nn", "sv", "da", "fi", "is", "zh", "hi", "es", "fr", "ar", "bn", "pt", "ru", "ur", "id", "de", "ja", "sw", "mr", "fa", "uk", "tr"];
const COUNTRIES = { NO: "Norway", SE: "Sweden", DK: "Denmark", FI: "Finland", IS: "Iceland" };

export function render(strings) {
  const names = {};
  for (const lang of LANGS) {
    const key = lang === "zh" ? "zh-Hans" : lang;
    names[lang] = {};
    for (const [code, english] of Object.entries(COUNTRIES)) {
      const value = lang === "en" ? english
        : strings[english]?.localizations?.[key]?.stringUnit?.value;
      names[lang][code] = value || english;
    }
  }
  return "// Generated by scripts/gen-copy.mjs from NordicCrypto/Localizable.xcstrings. Do not edit.\n"
    + `export const LANGS = ${JSON.stringify(LANGS)};\n`
    + `export const COUNTRY_NAMES = ${JSON.stringify(names, null, 1)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(JSON.parse(readFileSync(catalogue, "utf8")).strings);
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error("src/copy.js is out of date: run node scripts/gen-copy.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
  }
}
